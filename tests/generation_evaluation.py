
import json
import os
import time
from pathlib import Path

from dotenv import load_dotenv
from groq import Groq
from pydantic import BaseModel

from app.services.rag_service import RAGService
from app.services.context_builder import build_context
from app.services.qdrant_service import get_chunks_by_ids


# ============================================================
# LOAD ENVIRONMENT VARIABLES
# ============================================================

load_dotenv()


BASE_DIR = Path(__file__).resolve().parent

QUESTION_FILE = BASE_DIR / "question.json"

OUTPUT_FILE = (
    BASE_DIR / "generation_evaluation_results.json"
)

# Groq model used as external evaluator.
GROQ_MODEL = "openai/gpt-oss-120b"

# Number of questions to evaluate.
# Set to None to evaluate all questions.
MAX_QUESTIONS = None

# Number of chunks passed to the generation model.
TOP_K = 5

# Maximum tokens generated by Qwen.
MAX_NEW_TOKENS = 300

# Small delay between Groq requests.
REQUEST_DELAY_SECONDS = 1


# ============================================================
# GROQ EVALUATION SCHEMA
# ============================================================

class EvaluationResult(BaseModel):

    correctness: int

    relevance: int

    faithfulness: int

    explanation: str


# ============================================================
# GROQ EVALUATOR
# ============================================================

class GroqEvaluator:

    def __init__(self):

        print("\nInitializing Groq evaluator...")

        api_key = os.getenv("GROQ_API_KEY")

        if not api_key:

            raise RuntimeError(
                "GROQ_API_KEY environment variable "
                "is not set."
            )

        self.client = Groq(
            api_key=api_key
        )

        print(
            f"Groq evaluator initialized "
            f"using {GROQ_MODEL}"
        )

    def build_prompt(
        self,
        question: str,
        ground_truth_context: str,
        retrieved_context: str,
        generated_answer: str,
    ) -> str:

        return f"""
You are an expert evaluator for a
Retrieval-Augmented Generation (RAG) system.

Your task is to evaluate the generated answer.

IMPORTANT:
You must evaluate ONLY using the evidence provided
in this prompt.

Do NOT use:
- outside knowledge
- internet knowledge
- assumptions
- information not present in the supplied evidence

============================================================
QUESTION
============================================================

{question}


============================================================
GROUND-TRUTH EVIDENCE
============================================================

This evidence comes from the authoritative chunks
identified as ground truth for this question.

Use this evidence primarily to judge CORRECTNESS.

{ground_truth_context}


============================================================
ACTUAL RETRIEVED EVIDENCE
============================================================

These are the chunks that were actually supplied
to the generation model.

Use this evidence to judge FAITHFULNESS.

{retrieved_context}


============================================================
GENERATED ANSWER
============================================================

{generated_answer}


============================================================
EVALUATION CRITERIA
============================================================

1. CORRECTNESS

Determine whether the generated answer correctly
answers the question according to the ground-truth
evidence.

Scoring:

1 = Completely incorrect
2 = Mostly incorrect
3 = Partially correct
4 = Mostly correct
5 = Completely correct


2. RELEVANCE

Determine whether the generated answer directly
addresses the question without unnecessary or
unrelated information.

Scoring:

1 = Completely irrelevant
2 = Mostly irrelevant
3 = Partially relevant
4 = Mostly relevant
5 = Directly and completely relevant


3. FAITHFULNESS

Determine whether the claims in the generated answer
are supported by the ACTUAL RETRIEVED EVIDENCE that
was supplied to the generation model.

Important:

An answer can be CORRECT but NOT FAITHFUL.

For example, if the answer contains a fact that exists
in the ground-truth evidence but that fact was NOT
present in the retrieved evidence, the answer may be
correct but should receive a lower faithfulness score.

Scoring:

1 = Completely unsupported
2 = Mostly unsupported
3 = Partially supported
4 = Mostly supported
5 = Fully supported


============================================================
IMPORTANT
============================================================

Evaluate the answer itself.

Do not evaluate the quality of the retrieval system
directly.

Return:

- correctness
- relevance
- faithfulness
- a short explanation

Scores must be integers from 1 to 5.
"""

    def evaluate(
        self,
        question: str,
        ground_truth_context: str,
        retrieved_context: str,
        generated_answer: str,
    ) -> EvaluationResult:

        prompt = self.build_prompt(
            question=question,
            ground_truth_context=ground_truth_context,
            retrieved_context=retrieved_context,
            generated_answer=generated_answer,
        )

        response = self.client.chat.completions.create(

            model=GROQ_MODEL,

            messages=[
                {
                    "role": "system",
                    "content": (
                        "You are a strict RAG evaluation judge. "
                        "Evaluate only using the evidence provided. "
                        "Return the requested JSON structure."
                    ),
                },
                {
                    "role": "user",
                    "content": prompt,
                },
            ],

            temperature=0,

            response_format={
                "type": "json_schema",
                "json_schema": {
                    "name": "rag_evaluation",
                    "strict": True,
                    "schema": {
                        "type": "object",
                        "properties": {
                            "correctness": {
                                "type": "integer",
                                "minimum": 1,
                                "maximum": 5,
                            },
                            "relevance": {
                                "type": "integer",
                                "minimum": 1,
                                "maximum": 5,
                            },
                            "faithfulness": {
                                "type": "integer",
                                "minimum": 1,
                                "maximum": 5,
                            },
                            "explanation": {
                                "type": "string",
                            },
                        },
                        "required": [
                            "correctness",
                            "relevance",
                            "faithfulness",
                            "explanation",
                        ],
                        "additionalProperties": False,
                    },
                },
            },
        )

        response_text = (
            response.choices[0].message.content
        )

        if not response_text:

            raise RuntimeError(
                "Groq evaluator returned an empty response."
            )

        evaluation = EvaluationResult.model_validate_json(
            response_text
        )

        # --------------------------------------------------------
        # Validate score ranges.
        # --------------------------------------------------------

        scores = [
            evaluation.correctness,
            evaluation.relevance,
            evaluation.faithfulness,
        ]

        for score in scores:

            if not 1 <= score <= 5:

                raise ValueError(
                    f"Invalid Groq score: {score}. "
                    "Expected a value between 1 and 5."
                )

        return evaluation


# ============================================================
# HELPER FUNCTIONS
# ============================================================

def load_questions():

    with open(
        QUESTION_FILE,
        "r",
        encoding="utf-8",
    ) as file:

        data = json.load(file)

    return data


def save_results(results):

    with open(
        OUTPUT_FILE,
        "w",
        encoding="utf-8",
    ) as file:

        json.dump(
            results,
            file,
            indent=4,
            ensure_ascii=False,
        )


def build_gold_context(
    document_id: str,
    chunk_ids: list[int],
):

    gold_chunks = get_chunks_by_ids(
        document_id=document_id,
        chunk_ids=chunk_ids,
    )

    if not gold_chunks:

        raise RuntimeError(
            "Could not find ground-truth chunks "
            f"{chunk_ids} for document "
            f"{document_id}"
        )

    context = build_context(
        gold_chunks
    )

    return gold_chunks, context


def build_retrieved_context(
    sources: list[dict],
):

    return build_context(
        sources
    )


def calculate_average(
    evaluations: list[dict],
    metric: str,
):

    if not evaluations:

        return 0.0

    values = [
        item["evaluation"][metric]
        for item in evaluations
        if item.get("evaluation")
    ]

    if not values:

        return 0.0

    return sum(values) / len(values)


# ============================================================
# EVALUATE ONE PIPELINE
# ============================================================

def evaluate_pipeline(
    rag: RAGService,
    evaluator: GroqEvaluator,
    questions: list[dict],
    document_id: str,
    pipeline_name: str,
):

    results = []

    total = len(questions)

    print("\n")
    print("=" * 80)
    print(
        f"STARTING {pipeline_name.upper()} GENERATION EVALUATION"
    )
    print("=" * 80)

    for index, item in enumerate(
        questions,
        start=1,
    ):

        question_id = item["question_id"]

        question = item["question"]

        ground_truth_chunk_ids = (
            item["ground_truth_chunk_ids"]
        )

        print("\n")
        print("-" * 80)
        print(
            f"{pipeline_name.upper()} | "
            f"Question {index}/{total} | "
            f"ID: {question_id}"
        )
        print("-" * 80)

        print(
            f"Question: {question}"
        )

        print(
            f"Ground-truth chunks: "
            f"{ground_truth_chunk_ids}"
        )

        # ======================================================
        # GET GROUND-TRUTH EVIDENCE
        # ======================================================

        print(
            "\nLoading ground-truth chunks..."
        )

        gold_chunks, ground_truth_context = (
            build_gold_context(
                document_id=document_id,
                chunk_ids=ground_truth_chunk_ids,
            )
        )

        print(
            f"Loaded {len(gold_chunks)} "
            f"ground-truth chunks."
        )

        # ======================================================
        # GENERATE ANSWER
        # ======================================================

        print(
            "\nGenerating answer..."
        )

        use_reranker = (
            pipeline_name == "reranked"
        )

        start_time = time.time()

        rag_result = rag.answer(
            query=question,
            document_id=document_id,
            top_k=TOP_K,
            max_new_tokens=MAX_NEW_TOKENS,
            use_reranker=use_reranker,
        )

        generation_time = (
            time.time() - start_time
        )

        generated_answer = (
            rag_result["answer"]
        )

        sources = (
            rag_result["sources"]
        )

        print(
            "\nGenerated answer:"
        )

        print(
            generated_answer
        )

        print(
            f"\nGeneration time: "
            f"{generation_time:.2f} seconds"
        )

        # ======================================================
        # ACTUAL RETRIEVED CONTEXT
        # ======================================================

        retrieved_context = (
            build_retrieved_context(
                sources
            )
        )

        # ======================================================
        # GROQ EVALUATION
        # ======================================================

        print(
            "\nSending answer to Groq judge..."
        )

        evaluation = evaluator.evaluate(
            question=question,
            ground_truth_context=(
                ground_truth_context
            ),
            retrieved_context=(
                retrieved_context
            ),
            generated_answer=(
                generated_answer
            ),
        )

        print(
            "\nGroq evaluation:"
        )

        print(
            f"Correctness   : "
            f"{evaluation.correctness}/5"
        )

        print(
            f"Relevance     : "
            f"{evaluation.relevance}/5"
        )

        print(
            f"Faithfulness  : "
            f"{evaluation.faithfulness}/5"
        )

        print(
            f"Explanation   : "
            f"{evaluation.explanation}"
        )

        # ======================================================
        # STORE RESULT
        # ======================================================

        result = {

            "question_id": question_id,

            "question": question,

            "pipeline": pipeline_name,

            "ground_truth_chunk_ids": (
                ground_truth_chunk_ids
            ),

            "ground_truth_chunks": gold_chunks,

            "ground_truth_context": (
                ground_truth_context
            ),

            "generated_answer": (
                generated_answer
            ),

            "retrieved_sources": sources,

            "retrieved_context": (
                retrieved_context
            ),

            "generation_time_seconds": (
                round(
                    generation_time,
                    3
                )
            ),

            "evaluation": {

                "correctness": (
                    evaluation.correctness
                ),

                "relevance": (
                    evaluation.relevance
                ),

                "faithfulness": (
                    evaluation.faithfulness
                ),

                "explanation": (
                    evaluation.explanation
                ),
            },
        }

        results.append(result)

        print(
            "\nQuestion evaluation completed."
        )

        # Prevent hitting API too aggressively.
        if index < total:

            time.sleep(
                REQUEST_DELAY_SECONDS
            )

    return results


# ============================================================
# SUMMARY
# ============================================================

def create_summary(
    baseline_results,
    reranked_results,
):

    summary = {

        "baseline": {

            "questions_evaluated": (
                len(baseline_results)
            ),

            "average_correctness": round(
                calculate_average(
                    baseline_results,
                    "correctness",
                ),
                4,
            ),

            "average_relevance": round(
                calculate_average(
                    baseline_results,
                    "relevance",
                ),
                4,
            ),

            "average_faithfulness": round(
                calculate_average(
                    baseline_results,
                    "faithfulness",
                ),
                4,
            ),
        },

        "reranked": {

            "questions_evaluated": (
                len(reranked_results)
            ),

            "average_correctness": round(
                calculate_average(
                    reranked_results,
                    "correctness",
                ),
                4,
            ),

            "average_relevance": round(
                calculate_average(
                    reranked_results,
                    "relevance",
                ),
                4,
            ),

            "average_faithfulness": round(
                calculate_average(
                    reranked_results,
                    "faithfulness",
                ),
                4,
            ),
        },
    }

    return summary


# ============================================================
# MAIN
# ============================================================

def main():

    print("\n")
    print("=" * 80)
    print("RAG GENERATION EVALUATION")
    print("=" * 80)

    # --------------------------------------------------------
    # Load evaluation dataset
    # --------------------------------------------------------

    data = load_questions()

    document_id = data["document_id"]

    questions = data["questions"]

    if MAX_QUESTIONS is not None:

        questions = questions[
            :MAX_QUESTIONS
        ]

    print(
        f"\nDocument ID: {document_id}"
    )

    print(
        f"Questions to evaluate: "
        f"{len(questions)}"
    )

    print(
        f"Top K: {TOP_K}"
    )

    # --------------------------------------------------------
    # Initialize services ONCE.
    # --------------------------------------------------------

    print(
        "\nInitializing RAG service..."
    )

    rag = RAGService()

    evaluator = GroqEvaluator()

    # --------------------------------------------------------
    # BASELINE
    # --------------------------------------------------------

    baseline_results = evaluate_pipeline(
        rag=rag,
        evaluator=evaluator,
        questions=questions,
        document_id=document_id,
        pipeline_name="baseline",
    )

    # --------------------------------------------------------
    # RERANKED
    # --------------------------------------------------------

    reranked_results = evaluate_pipeline(
        rag=rag,
        evaluator=evaluator,
        questions=questions,
        document_id=document_id,
        pipeline_name="reranked",
    )

    # --------------------------------------------------------
    # SUMMARY
    # --------------------------------------------------------

    summary = create_summary(
        baseline_results=baseline_results,
        reranked_results=reranked_results,
    )

    # --------------------------------------------------------
    # FINAL OUTPUT
    # --------------------------------------------------------

    output = {

        "metadata": {

            "document_id": document_id,

            "filename": data.get(
                "filename"
            ),

            "retrieval_top_k": data.get(
                "retrieval_top_k"
            ),

            "rerank_top_k": data.get(
                "rerank_top_k"
            ),

            "generation_top_k": TOP_K,

            "max_new_tokens": (
                MAX_NEW_TOKENS
            ),

            "groq_model": GROQ_MODEL,

            "judge": "Groq",

            "number_of_questions": (
                len(questions)
            ),
        },

        "summary": summary,

        "baseline_results": (
            baseline_results
        ),

        "reranked_results": (
            reranked_results
        ),
    }

    save_results(output)

    # --------------------------------------------------------
    # Print final summary
    # --------------------------------------------------------

    print("\n")
    print("=" * 80)
    print("FINAL GENERATION EVALUATION")
    print("=" * 80)

    print(
        "\n"
        "                         BASELINE     RERANKED"
    )

    print(
        "--------------------------------------------------------"
    )

    print(
        f"Correctness          "
        f"{summary['baseline']['average_correctness']:.4f}"
        f"        "
        f"{summary['reranked']['average_correctness']:.4f}"
    )

    print(
        f"Relevance            "
        f"{summary['baseline']['average_relevance']:.4f}"
        f"        "
        f"{summary['reranked']['average_relevance']:.4f}"
    )

    print(
        f"Faithfulness         "
        f"{summary['baseline']['average_faithfulness']:.4f}"
        f"        "
        f"{summary['reranked']['average_faithfulness']:.4f}"
    )

    print(
        "\n"
        f"Results saved to:\n"
        f"{OUTPUT_FILE}"
    )

    print(
        "\nEvaluation completed successfully."
    )


if __name__ == "__main__":

    main()

